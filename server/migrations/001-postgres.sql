CREATE TABLE IF NOT EXISTS users (
 id text PRIMARY KEY, username text UNIQUE NOT NULL, display_name text NOT NULL,
 password_hash text NOT NULL, created_at text NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash text PRIMARY KEY, user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 csrf text NOT NULL, expires_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_by_user ON sessions(user_id);
CREATE INDEX IF NOT EXISTS session_expiry ON sessions(expires_at);
CREATE TABLE IF NOT EXISTS lesson_progress (
 user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE, lesson_id text NOT NULL,
 is_read integer NOT NULL DEFAULT 0, last_tab text NOT NULL DEFAULT 'learn',
 updated_at text NOT NULL DEFAULT (CURRENT_TIMESTAMP::text), PRIMARY KEY(user_id,lesson_id)
);
CREATE TABLE IF NOT EXISTS exercise_progress (
 user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE, exercise_id text NOT NULL,
 answer text NOT NULL DEFAULT '', attempts integer NOT NULL DEFAULT 0,
 correct integer NOT NULL DEFAULT 0, independent integer NOT NULL DEFAULT 0,
 hints_used integer NOT NULL DEFAULT 0, solution_seen integer NOT NULL DEFAULT 0,
 self_reviewed integer NOT NULL DEFAULT 0, updated_at text NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
 PRIMARY KEY(user_id,exercise_id)
);
CREATE TABLE IF NOT EXISTS attempts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE, exercise_id text NOT NULL,
 answer text NOT NULL, correct integer NOT NULL, assisted integer NOT NULL,
 created_at text NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);
CREATE INDEX IF NOT EXISTS attempt_user ON attempts(user_id,exercise_id);
CREATE TABLE IF NOT EXISTS auth_limits (
 key text PRIMARY KEY, count integer NOT NULL, expires_at bigint NOT NULL
);
